a = 10
b = 3

#Suma 
suma = a + b #13
print(f"Suma: {suma}")

#Resta
resta = a - b #7
print(f"Resta: {resta}")


#Multiplicación
multiplicacion = a * b #30
print(f"Multiplicación: {multiplicacion}")

#División
division = a / b #Flotante 3.33333333333
print(f"División: {division}")
print(f"Podemos usar division:.2f para sacar dos decimales: {division:.2f}")


#division_entera
division_entera = a // b
print(f"División entera: {division_entera}")

#Módulo
mod = a % b # 3 x 3 + + 1 <- el resto
print(f"Módulo: {mod}")

#Exponente
exponente = a**b
print(f"Exponente de {a}^{b}: {exponente}")